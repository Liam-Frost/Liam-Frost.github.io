import { normalizeAdminPath } from "@liam-frost/shared";
import { z } from "zod";

import { IpList } from "../lib/ip-list";

const DEV_CORS_ORIGINS = [
  "http://localhost:5173",
  "http://127.0.0.1:5173",
  "http://localhost:4173",
  "http://127.0.0.1:4173"
];

const optionalString = z
  .string()
  .optional()
  .transform((value) => value?.trim() || undefined);

const booleanFlag = z
  .enum(["true", "false"], { message: "must be true or false" })
  .optional()
  .transform((value) => (value === undefined ? undefined : value === "true"));

const csv = optionalString.transform((value) =>
  value ? value.split(",").map((item) => item.trim()).filter(Boolean) : []
);

const envSchema = z.object({
  NODE_ENV: optionalString,
  HOST: optionalString.default("0.0.0.0"),
  PORT: z.coerce.number().int().min(1).max(65535).default(8787),
  CORS_ORIGIN: csv,
  TRUST_PROXY: booleanFlag,
  DATABASE_URL: optionalString,

  ADMIN_USERNAME: optionalString,
  ADMIN_PASSWORD_HASH: optionalString.refine(
    (value) => !value || /^scrypt:v1:[^:]+:[^:]+$/.test(value),
    "must be generated by `npm run auth:hash`"
  ),
  ADMIN_SESSION_SECRET: optionalString.refine(
    (value) => !value || value.length >= 32,
    "must be at least 32 characters"
  ),
  ADMIN_SESSION_TTL_SECONDS: z.coerce
    .number()
    .int()
    .min(300)
    .max(60 * 60 * 24 * 30)
    .default(60 * 60 * 8),
  ADMIN_COOKIE_NAME: optionalString.refine(
    (value) => !value || /^[A-Za-z0-9_-]+$/.test(value),
    "may only contain letters, digits, '-' and '_'"
  ),
  ADMIN_COOKIE_SECURE: booleanFlag,
  ADMIN_PATH: optionalString,
  ADMIN_ALLOWED_IPS: csv
});

export type AdminConfig = {
  /** True when both the password hash and session secret are set. */
  configured: boolean;
  username: string;
  passwordHash: string;
  sessionSecret: string;
  sessionTtlSeconds: number;
  cookieName: string;
  cookieSecure: boolean;
  path: string;
  allowedIps: IpList;
};

export type AppConfig = {
  production: boolean;
  host: string;
  port: number;
  corsOrigins: string[];
  trustProxy: boolean;
  databaseUrl?: string;
  admin: AdminConfig;
};

export class ConfigError extends Error {
  constructor(readonly issues: string[]) {
    super(`Invalid configuration:\n${issues.map((issue) => `  - ${issue}`).join("\n")}`);
    this.name = "ConfigError";
  }
}

/** Parses and validates environment variables. Throws ConfigError listing every problem at once. */
export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const parsed = envSchema.safeParse(env);
  if (!parsed.success) {
    throw new ConfigError(parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`));
  }

  const values = parsed.data;
  const issues: string[] = [];
  const production = values.NODE_ENV === "production";

  const passwordHash = values.ADMIN_PASSWORD_HASH ?? "";
  const sessionSecret = values.ADMIN_SESSION_SECRET ?? "";
  if (Boolean(passwordHash) !== Boolean(sessionSecret)) {
    issues.push("ADMIN_PASSWORD_HASH and ADMIN_SESSION_SECRET must be set together");
  }

  let adminPath = "";
  try {
    adminPath = normalizeAdminPath(values.ADMIN_PATH);
  } catch (error) {
    issues.push((error as Error).message);
  }

  let allowedIps = new IpList([]);
  try {
    allowedIps = new IpList(values.ADMIN_ALLOWED_IPS);
  } catch (error) {
    issues.push(`ADMIN_ALLOWED_IPS: ${(error as Error).message}`);
  }

  if (issues.length) {
    throw new ConfigError(issues);
  }

  return {
    production,
    host: values.HOST,
    port: values.PORT,
    corsOrigins: values.CORS_ORIGIN.length ? values.CORS_ORIGIN : production ? [] : DEV_CORS_ORIGINS,
    trustProxy: values.TRUST_PROXY ?? false,
    databaseUrl: values.DATABASE_URL,
    admin: {
      configured: Boolean(passwordHash && sessionSecret),
      username: values.ADMIN_USERNAME ?? "admin",
      passwordHash,
      sessionSecret,
      sessionTtlSeconds: values.ADMIN_SESSION_TTL_SECONDS,
      cookieName: values.ADMIN_COOKIE_NAME ?? "lf_admin_session",
      cookieSecure: values.ADMIN_COOKIE_SECURE ?? production,
      path: adminPath,
      allowedIps
    }
  };
}
