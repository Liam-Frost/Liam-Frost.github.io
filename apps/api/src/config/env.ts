import { normalizeAdminPath } from "@liam-frost/shared";
import { z } from "zod";

import { IpList } from "../lib/ip-list";

const DEV_CORS_ORIGINS = [
  "http://localhost:5173",
  "http://127.0.0.1:5173",
  "http://localhost:4173",
  "http://127.0.0.1:4173"
];

const optionalString = z
  .string()
  .optional()
  .transform((value) => value?.trim() || undefined);

const booleanFlag = z
  .enum(["true", "false"], { message: "must be true or false" })
  .optional()
  .transform((value) => (value === undefined ? undefined : value === "true"));

/** Blank values (`PORT=`) mean "use the default", like blank strings do. */
const optionalNumber = z.preprocess((value) => (typeof value === "string" && value.trim() === "" ? undefined : value), z.coerce.number().int().optional());

const csv = optionalString.transform((value) =>
  value ? value.split(",").map((item) => item.trim()).filter(Boolean) : []
);

const envSchema = z.object({
  NODE_ENV: optionalString,
  HOST: optionalString.default("0.0.0.0"),
  PORT: optionalNumber.pipe(z.number().int().min(1).max(65535).default(8787)),
  CORS_ORIGIN: csv,
  TRUST_PROXY: csv,

  ADMIN_USERNAME: optionalString,
  ADMIN_PASSWORD_HASH: optionalString.refine(
    (value) => !value || /^scrypt:v1:[^:]+:[^:]+$/.test(value),
    "must be generated by `npm run auth:hash`"
  ),
  ADMIN_SESSION_SECRET: optionalString.refine(
    (value) => !value || value.length >= 32,
    "must be at least 32 characters"
  ),
  ADMIN_SESSION_TTL_SECONDS: optionalNumber.pipe(
    z
      .number()
      .int()
      .min(300)
      .max(60 * 60 * 24 * 30)
      .default(60 * 60 * 8)
  ),
  ADMIN_COOKIE_NAME: optionalString.refine(
    (value) => !value || /^[A-Za-z0-9_-]+$/.test(value),
    "may only contain letters, digits, '-' and '_'"
  ),
  ADMIN_COOKIE_SECURE: booleanFlag,
  ADMIN_PATH: optionalString,
  ADMIN_ALLOWED_IPS: csv,

  UPLOAD_DIR: optionalString,
  UPLOAD_MAX_MB: optionalNumber.pipe(z.number().int().min(1).max(200).default(40)),
  TMDB_API_KEY: optionalString,
  GOOGLE_BOOKS_API_KEY: optionalString,
  SPOTIFY_CLIENT_ID: optionalString,
  SPOTIFY_CLIENT_SECRET: optionalString,
  SPOTIFY_REDIRECT_URI: optionalString
});

export type AdminConfig = {
  /** True when both the password hash and session secret are set. */
  configured: boolean;
  username: string;
  passwordHash: string;
  sessionSecret: string;
  sessionTtlSeconds: number;
  cookieName: string;
  cookieSecure: boolean;
  path: string;
  allowedIps: IpList;
};

export type AppConfig = {
  production: boolean;
  host: string;
  port: number;
  corsOrigins: string[];
  /** false, true (any hop; only safe when the API port is not publicly reachable), or the proxy addresses to trust. */
  trustProxy: boolean | string[];
  admin: AdminConfig;
  uploads: {
    /** Absolute or relative directory for uploaded images; defaults to apps/api/uploads. */
    dir?: string;
    maxBytes: number;
  };
  /** TMDB API key (v3) or read access token (v4) for collection searches; empty disables TMDB. */
  tmdbApiKey: string;
  /** Google Books API key; empty disables Google Books as a book source. */
  googleBooksApiKey: string;
  /** Spotify developer app for importing the admin's Liked Songs and playlists; null when not set up. */
  spotify: { clientId: string; clientSecret: string; redirectUri: string } | null;
};

export class ConfigError extends Error {
  constructor(readonly issues: string[]) {
    super(`Invalid configuration:\n${issues.map((issue) => `  - ${issue}`).join("\n")}`);
    this.name = "ConfigError";
  }
}

/** Parses and validates environment variables. Throws ConfigError listing every problem at once. */
export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const parsed = envSchema.safeParse(env);
  if (!parsed.success) {
    throw new ConfigError(parsed.error.issues.map((issue) => `${issue.path.join(".")}: ${issue.message}`));
  }

  const values = parsed.data;
  const issues: string[] = [];
  const production = values.NODE_ENV === "production";

  const passwordHash = values.ADMIN_PASSWORD_HASH ?? "";
  const sessionSecret = values.ADMIN_SESSION_SECRET ?? "";
  if (Boolean(passwordHash) !== Boolean(sessionSecret)) {
    issues.push("ADMIN_PASSWORD_HASH and ADMIN_SESSION_SECRET must be set together");
  }

  const spotifyId = values.SPOTIFY_CLIENT_ID ?? "";
  const spotifySecret = values.SPOTIFY_CLIENT_SECRET ?? "";
  if (Boolean(spotifyId) !== Boolean(spotifySecret)) {
    issues.push("SPOTIFY_CLIENT_ID and SPOTIFY_CLIENT_SECRET must be set together");
  }
  // Spotify only allows plain HTTP redirects to loopback IPs; the default matches a local API.
  const spotifyRedirect = values.SPOTIFY_REDIRECT_URI ?? `http://127.0.0.1:${values.PORT}/api/admin/spotify/callback`;
  try {
    const url = new URL(spotifyRedirect);
    if (!["http:", "https:"].includes(url.protocol)) throw new Error("not http(s)");
  } catch {
    issues.push("SPOTIFY_REDIRECT_URI must be an http(s) URL");
  }

  let adminPath = "";
  try {
    adminPath = normalizeAdminPath(values.ADMIN_PATH);
  } catch (error) {
    issues.push((error as Error).message);
  }

  let trustProxy: boolean | string[] = false;
  const [firstProxy, ...otherProxies] = values.TRUST_PROXY;
  if (firstProxy === "true" && otherProxies.length === 0) {
    trustProxy = true;
  } else if (firstProxy && firstProxy !== "false") {
    try {
      // Validates every entry is an IP or CIDR range; Fastify gets the original strings.
      new IpList(values.TRUST_PROXY);
      trustProxy = values.TRUST_PROXY;
    } catch (error) {
      issues.push(`TRUST_PROXY: must be true, false, or a list of proxy IPs / CIDR ranges (${(error as Error).message})`);
    }
  }

  let allowedIps = new IpList([]);
  try {
    allowedIps = new IpList(values.ADMIN_ALLOWED_IPS);
  } catch (error) {
    issues.push(`ADMIN_ALLOWED_IPS: ${(error as Error).message}`);
  }

  if (issues.length) {
    throw new ConfigError(issues);
  }

  return {
    production,
    host: values.HOST,
    port: values.PORT,
    corsOrigins: values.CORS_ORIGIN.length ? values.CORS_ORIGIN : production ? [] : DEV_CORS_ORIGINS,
    trustProxy,
    admin: {
      configured: Boolean(passwordHash && sessionSecret),
      username: values.ADMIN_USERNAME ?? "admin",
      passwordHash,
      sessionSecret,
      sessionTtlSeconds: values.ADMIN_SESSION_TTL_SECONDS,
      cookieName: values.ADMIN_COOKIE_NAME ?? "lf_admin_session",
      cookieSecure: values.ADMIN_COOKIE_SECURE ?? production,
      path: adminPath,
      allowedIps
    },
    uploads: {
      dir: values.UPLOAD_DIR,
      maxBytes: values.UPLOAD_MAX_MB * 1024 * 1024
    },
    tmdbApiKey: values.TMDB_API_KEY ?? "",
    googleBooksApiKey: values.GOOGLE_BOOKS_API_KEY ?? "",
    spotify: spotifyId && spotifySecret ? { clientId: spotifyId, clientSecret: spotifySecret, redirectUri: spotifyRedirect } : null
  };
}
