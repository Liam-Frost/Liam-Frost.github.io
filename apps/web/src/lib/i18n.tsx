const DICT: Record<Lang, Record<Key, string>> = { zh, "zh-Hant": zhHant, en, fr, ja };

const STORAGE_KEY = "lang";

const LANGS: Lang[] = ["zh", "zh-Hant", "en", "fr", "ja"];

/** Case-insensitive match that returns the canonical code ("zh-hant" → "zh-Hant"), which DICT is keyed by. */
function normalizeLang(value: string | null): Lang | null {
  if (!value) return null;
  const v = value.toLowerCase();
  return LANGS.find((lang) => lang.toLowerCase() === v) ?? null;
}

function detectLang(): Lang {
  try {
    const saved = normalizeLang(localStorage.getItem(STORAGE_KEY));
    if (saved) return saved;
  } catch {
    // ignore
  }

  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk") || nav.startsWith("zh-hant"))
    return "zh-Hant";
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("en")) return "en";
  return "zh";
}

function langToHtmlLang(lang: Lang) {
  if (lang === "zh") return "zh-Hans";
  if (lang === "zh-Hant") return "zh-Hant";
  if (lang === "ja") return "ja";
  return lang;
}

function format(template: string, params?: Record<string, string | number>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const v = params[key];
    return v === undefined ? `{${key}}` : String(v);
  });
}

type I18nContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, params?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => detectLang());

  useEffect(() => {
    document.documentElement.setAttribute("data-lang", lang);
    document.documentElement.lang = langToHtmlLang(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // ignore
    }
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => {
    // Never render nothing because of an unknown language; fall back to Simplified Chinese.
    const dict = DICT[lang] ?? DICT.zh;
    return {
      lang,
      setLang,
      t: (key, params) => format(dict[key], params)
    };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
